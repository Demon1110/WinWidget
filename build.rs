// Embeds the icon and the version block into the Windows executable, and packs the whole
// `assets\` tree into it as well (see `src/core/assets.rs`).
//
// The resource compiler only exists on Windows toolchains, so the icon step returns early on
// every other target: the crate still builds on Linux/macOS for development. The asset table has
// no such dependency and is always generated.

use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=assets");
    println!("cargo:rerun-if-changed=assets/logo.ico");
    println!("cargo:rerun-if-changed=build.rs");

    embed_assets();

    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }

    let mut res = winresource::WindowsResource::new();
    res.set_icon("assets/logo.ico")
        .set("ProductName", "WinWidget")
        .set("FileDescription", "WinWidget — Windows 桌面小组件")
        .set("CompanyName", "WinWidget")
        .set("LegalCopyright", "GPL-3.0-only · WinWidget contributors")
        .set("OriginalFilename", "winwidget.exe")
        .set_language(0x0804); // zh-CN, matches the default UI language

    res.compile()
        .expect("embedding resources needs rc.exe (MSVC) or windres (MinGW) on PATH");
}

/// Writes `assets_embed.rs` into `OUT_DIR`: one entry per file under `assets/`, each >= 256 bytes
/// deflated so the binary stays around one download's worth instead of five.
///
/// `docs/m<N>` (the milestone screenshots, ~13 MB of repository material) is skipped — nothing at
/// runtime reads it, and the developer guide is a single self-contained HTML file.
fn embed_assets() {
    let root =
        Path::new(&std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR")).join("assets");
    let out = std::env::var("OUT_DIR").expect("OUT_DIR");
    let blobs = Path::new(&out).join("asset-blobs");
    let _ = std::fs::remove_dir_all(&blobs);
    std::fs::create_dir_all(&blobs).expect("create the blob directory");

    let mut rels: Vec<String> = Vec::new();
    collect(&root, "", &mut rels);
    rels.sort();

    let mut src = String::from(
        "// @generated by build.rs — every file under assets/, deflated where it pays.\n\
         pub static ASSETS: &[Asset] = &[\n",
    );
    for (index, rel) in rels.iter().enumerate() {
        let full = root.join(rel.replace('/', std::path::MAIN_SEPARATOR_STR));
        let Ok(bytes) = std::fs::read(&full) else {
            continue;
        };
        let packed = bytes.len() >= 256;
        let data = if packed { deflate(&bytes) } else { bytes };
        let blob = blobs.join(format!("{index}.bin"));
        std::fs::write(&blob, &data).expect("write an asset blob");
        src.push_str(&format!(
            "    Asset {{ path: {rel:?}, packed: {packed}, bytes: include_bytes!({:?}) }},\n",
            blob.to_string_lossy().replace('\\', "/")
        ));
    }
    src.push_str("];\n");
    std::fs::write(Path::new(&out).join("assets_embed.rs"), src).expect("write assets_embed.rs");
}

fn collect(root: &Path, rel: &str, out: &mut Vec<String>) {
    let dir = if rel.is_empty() {
        root.to_path_buf()
    } else {
        root.join(rel)
    };
    let Ok(entries) = std::fs::read_dir(&dir) else {
        return;
    };
    for entry in entries.flatten() {
        let name = entry.file_name().to_string_lossy().to_string();
        let child = if rel.is_empty() {
            name.clone()
        } else {
            format!("{rel}/{name}")
        };
        if entry.path().is_dir() {
            if !skip(&child) {
                collect(root, &child, out);
            }
        } else if !skip(&child) {
            out.push(child);
        }
    }
}

/// True for `docs/m0` … `docs/m9` and the files inside them.
fn skip(rel: &str) -> bool {
    let Some(rest) = rel.strip_prefix("docs/") else {
        return false;
    };
    let last = rest.rsplit('/').next().unwrap_or("");
    last.len() > 1 && last.starts_with('m') && last[1..].chars().all(|c| c.is_ascii_digit())
}

fn deflate(bytes: &[u8]) -> Vec<u8> {
    use flate2::write::DeflateEncoder;
    use flate2::Compression;
    use std::io::Write;

    let mut encoder = DeflateEncoder::new(Vec::new(), Compression::best());
    encoder.write_all(bytes).expect("deflate an asset");
    encoder.finish().expect("deflate an asset")
}
